#!/usr/bin/env python3
"""Writes src/colormaps.ts from Enki's built-in colour map atlas (read only):
~/dev/shaderEditor/ShaderEditor/app/src/main/res/raw/colormaps.png (one map per
row, 256 steps low to high) and its row names, tools/colormaps/names.txt:
Ready's maps (Brewer, inferno, terrain), then the CET Perceptually Uniform
Colour Maps (Peter Kovesi, CC BY 4.0, https://colorcet.com). Stored as 8-bit
RGB, base64. Usage: python3 lab/colormaps-import.py
"""
import base64
import os

from PIL import Image

ENKI = os.path.expanduser("~/dev/shaderEditor/ShaderEditor")
im = Image.open(f"{ENKI}/app/src/main/res/raw/colormaps.png").convert("RGB")
names = [n.strip() for n in open(f"{ENKI}/tools/colormaps/names.txt") if n.strip()]
assert im.size == (256, len(names)), (im.size, len(names))
data = base64.b64encode(im.tobytes()).decode()
with open("src/colormaps.ts", "w") as f:
	f.write("// Generated by lab/colormaps-import.py from Enki's colour map atlas: Ready's maps (Brewer,\n")
	f.write("// inferno, terrain), then the CET Perceptually Uniform Colour Maps (Peter Kovesi, CC BY 4.0,\n")
	f.write("// https://colorcet.com). One map per row, 256 steps low to high, 8-bit RGB.\n")
	f.write(f"export const COLORMAP_NAMES: string[] = {names!r};\n".replace("'", '"'))
	f.write(f'export const COLORMAP_RGB = "{data}";\n')
print(len(names), "maps,", len(data), "base64 chars")
